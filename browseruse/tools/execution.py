    def executor_tool(json_plan: str, delay=0.5):
        """
        Executes a JSON plan generated by the CommandAgent.
        Uses drag_tool.click and drag_tool.drag_and_drop for each step.
        """
        try:
            plan = json.loads(json_plan)
        except json.JSONDecodeError as e:
            print("Invalid JSON plan:", e)
            return
        
        steps = plan.get("steps", [])
        
        for step in steps:
            step_num = step.get("step")
            category = step.get("category")
            block = step.get("block")
            start = step.get("start_position")
